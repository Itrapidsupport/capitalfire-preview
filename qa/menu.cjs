// Menu checks: iPhone menu open (fits, no overflow, tap targets) + desktop services mega panel.
const { chromium, webkit, devices } = require('playwright')
const path = require('node:path')
;(async () => {
  const base = (process.argv[2] || 'https://itrapidsupport.github.io/capitalfire-preview/').replace(/\/?$/, '/')
  const out = process.argv[3] || path.join(__dirname, 'out')
  const w = await webkit.launch()
  const c = await w.newContext({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 } })
  const p = await c.newPage()
  await p.goto(base + 'services/cctv/', { waitUntil: 'networkidle' })
  await p.waitForTimeout(800)
  await p.tap('button[aria-controls="mobile-menu"]')
  await p.waitForTimeout(1200)
  const m = await p.evaluate(() => {
    const menu = document.getElementById('mobile-menu')
    const links = [...menu.querySelectorAll('a')]
    const small = links.filter((a) => a.getBoundingClientRect().height < 44).map((a) => a.textContent.trim())
    const over = links.filter((a) => a.getBoundingClientRect().right > innerWidth + 1).map((a) => a.textContent.trim())
    return { visible: !menu.hidden, links: links.length, small, over, sw: menu.scrollWidth, cw: menu.clientWidth, sh: menu.scrollHeight, ch: menu.clientHeight }
  })
  console.log('iphone menu', JSON.stringify(m))
  await p.screenshot({ path: path.join(out, 'menu-iphone-open.png') })
  await p.evaluate(() => document.getElementById('mobile-menu').scrollTo(0, 9999))
  await p.waitForTimeout(300)
  await p.screenshot({ path: path.join(out, 'menu-iphone-open-bottom.png') })
  await p.tap('button[aria-controls="mobile-menu"]')
  await p.waitForTimeout(500)
  console.log('menu closed', await p.evaluate(() => document.getElementById('mobile-menu').hidden))
  await w.close()
  const b = await chromium.launch()
  const d = await b.newPage({ viewport: { width: 1440, height: 900 } })
  await d.goto(base, { waitUntil: 'networkidle' })
  await d.hover('header nav a[href$="/services"]')
  await d.waitForTimeout(700)
  await d.screenshot({ path: path.join(out, 'menu-desktop-services.png') })
  await b.close()
})()
