// Route transition check: click internal links (desktop nav, mobile menu, in-page card) and assert the route
// changed, the curtain finished (hidden), and the new page's h1 is visible. Mid-transition frame is saved.
const { chromium, webkit, devices } = require('playwright')
const path = require('node:path')
;(async () => {
  const base = (process.argv[2] || 'http://localhost:4180/capitalfire-preview/').replace(/\/?$/, '/')
  const out = process.argv[3] || path.join(__dirname, 'out')
  const fails = []
  const state = (p) => p.evaluate(() => ({ path: location.pathname, curtain: getComputedStyle(document.querySelector('.ax-curtain')).visibility, h1: document.querySelector('h1')?.textContent?.trim() }))
  const b = await chromium.launch()
  const d = await b.newPage({ viewport: { width: 1440, height: 900 } })
  await d.goto(base, { waitUntil: 'networkidle' })
  await d.click('header nav a[href$="/projects"]')
  await d.waitForTimeout(350)
  await d.screenshot({ path: path.join(out, 'transition-mid-desktop.png') })
  await d.waitForTimeout(1800)
  let s = await state(d); console.log('desktop nav ->', JSON.stringify(s))
  if (!s.path.endsWith('/projects') || s.curtain !== 'hidden') fails.push('desktop nav')
  await d.click('footer a[href$="/services/cctv"]'); await d.waitForTimeout(2200)
  s = await state(d); console.log('footer link ->', JSON.stringify(s))
  if (!s.path.endsWith('/services/cctv') || s.curtain !== 'hidden') fails.push('footer link')
  await d.goBack(); await d.waitForTimeout(1500)
  s = await state(d); console.log('back ->', JSON.stringify(s))
  if (!s.path.endsWith('/projects')) fails.push('back button')
  await b.close()
  const w = await webkit.launch()
  const m = await (await w.newContext({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 } })).newPage()
  await m.goto(base, { waitUntil: 'networkidle' })
  await m.tap('button[aria-controls="mobile-menu"]'); await m.waitForTimeout(800)
  await m.tap('#mobile-menu a[href$="/about"]'); await m.waitForTimeout(2400)
  s = await state(m); const menuHidden = await m.evaluate(() => document.getElementById('mobile-menu').hidden)
  console.log('mobile menu ->', JSON.stringify(s), 'menuHidden', menuHidden)
  if (!s.path.endsWith('/about') || s.curtain !== 'hidden' || !menuHidden) fails.push('mobile menu nav')
  await w.close()
  console.log(fails.length ? 'FAIL ' + fails.join(', ') : 'PASS')
})()
